#!/usr/bin/env python3
"""Generates src/light.css: a light-theme override layer derived from src/index.css hard-coded colours."""
import re, tinycss2
SRC = open("src/index.css").read()
SKIP_SEL = re.compile(r"data-theme|^\s*(html|:root|body)\b|\.(hero|name|boot|sheet|modal|pm-|pal|toast|cursor|grain|nav|logo|chip-btn|burger|mark|skip|svc)\b|::selection|\.scroll-progress|\.progress|\.card-idx|\.vis|\.card-media|\.shot|\.shotm|\.glare|\.pcover|\.pm\b|\.pm-|\.badge-float|\.hero-|\.cta-row|\.dot-live|\.frame|\.ring-text|\.role-line|\.role-swap|\.scroll-cue|\.slash|\.tint|\.arr")
HEX = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
RGBA = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)")
def parse_hex(h):
    h = h.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
    return r, g, b, a
def lum(r, g, b): return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255
def is_gold(r, g, b): return r > b + 30 and r >= g and g > b and r > 120
def out(r, g, b, a): return f"rgba({r},{g},{b},{round(a,3)})" if a < 1 else "#%02x%02x%02x" % (r, g, b)
def conv(r, g, b, a, prop):
    L = lum(r, g, b)
    textlike = prop in ("color", "fill", "stroke", "-webkit-text-stroke", "caret-color", "text-decoration-color", "-webkit-text-fill-color")
    if textlike:
        if is_gold(r, g, b): return out(138, 106, 44, a) if L < 0.85 else out(154, 118, 50, a)
        if L > 0.8: return out(27, 30, 38, a)
        if L > 0.5: return out(89, 96, 112, a)
        return None
    if prop in ("box-shadow", "text-shadow"):
        return out(40, 34, 20, round(a * 0.55, 3)) if L < 0.25 else None
    # surfaces / borders
    if is_gold(r, g, b): return None
    if L < 0.25:   # dark surface -> ivory family
        t = min(1, L / 0.2)
        base = (246, 242, 233); deep = (229, 221, 202)
        return out(*[round(base[i] + (deep[i] - base[i]) * t) for i in range(3)], a)
    if L > 0.85:   # white-ish translucent overlay -> warm ink tint
        return out(40, 34, 20, min(1, a * 0.85))
    return None
def conv_value(val, prop):
    changed = False
    def h(m):
        nonlocal changed
        r, g, b, a = parse_hex(m.group(0)); c = conv(r, g, b, a, prop)
        if c: changed = True; return c
        return m.group(0)
    def rg(m):
        nonlocal changed
        r, g, b = int(m.group(1)), int(m.group(2)), int(m.group(3)); a = float(m.group(4)) if m.group(4) else 1.0
        c = conv(r, g, b, a, prop)
        if c: changed = True; return c
        return m.group(0)
    v = HEX.sub(h, val); v = RGBA.sub(rg, v)
    return v if changed else None
PROPS = re.compile(r"^(color|fill|stroke|-webkit-text-stroke|background|background-color|background-image|border(-[a-z]+)*(-color)?|outline(-color)?|box-shadow|text-shadow|-webkit-text-fill-color)$")
def nv_check(v): return v
def decls(content):
    res = []
    for d in tinycss2.parse_declaration_list(content, skip_whitespace=True, skip_comments=True):
        if d.type != "declaration" or not PROPS.match(d.lower_name): continue
        val = tinycss2.serialize(d.value).strip()
        if "var(" in val and not HEX.search(val) and not RGBA.search(val): continue
        prop = d.lower_name
        base = "color" if prop in ("color", "fill", "stroke", "-webkit-text-fill-color") else ("-webkit-text-stroke" if prop == "-webkit-text-stroke" else prop)
        nv = conv_value(val, base)
        name = "background-image" if d.lower_name == "background" and "gradient(" in val else d.name
        if nv: res.append(f"{name}: {nv}{' !important' if d.important else ''};")
    return res
def rules(nodes, wrap=None, acc=None):
    for n in nodes:
        if n.type == "qualified-rule":
            sel = tinycss2.serialize(n.prelude).strip()
            sels = [s.strip() for s in sel.split(",") if s.strip() and not SKIP_SEL.search(s.strip())]
            if not sels: continue
            ds = decls(n.content)
            if ds: acc.append((wrap, ",".join(f'html[data-theme="light"] {s}' for s in sels), " ".join(ds)))
        elif n.type == "at-rule" and n.lower_at_keyword in ("media", "supports") and n.content:
            rules(tinycss2.parse_rule_list(n.content, skip_whitespace=True, skip_comments=True), "@" + n.lower_at_keyword + " " + tinycss2.serialize(n.prelude).strip(), acc)
acc = []
rules(tinycss2.parse_stylesheet(SRC, skip_whitespace=True, skip_comments=True), None, acc)
lines = ["/* AUTO-GENERATED by scripts/gen_light.py — light-theme overrides derived from index.css */"]
for wrap, sel, body in acc:
    lines.append(f"{wrap} {{ {sel} {{ {body} }} }}" if wrap else f"{sel} {{ {body} }}")
lines.append("""
/* manual tail: gradient-clipped headings */
html[data-theme="light"] .h2 { background-image: linear-gradient(95deg, #1b1e26 0%, #1b1e26 48%, #8a6a2c 100%); }
html[data-theme="light"] [dir="rtl"] .h2 { background-image: linear-gradient(265deg, #1b1e26 0%, #1b1e26 48%, #8a6a2c 100%); }
html[data-theme="light"] .hm-cell { background: rgba(40,34,20,.07); }
html[data-theme="light"] .pm .tags span { color: #e4e9f8; }
html[data-theme="light"] .pm .btn.ghost { color: #f3eee3; border-color: rgba(226,218,200,.3); background: rgba(255,255,255,.05); }
html[data-theme="light"] .pm .btn.primary { color: #0b0e13; background: linear-gradient(135deg, #f0dba5, #c9a45e); }
html[data-theme="light"] .pm li, html[data-theme="light"] .pm p, html[data-theme="light"] .pm h2, html[data-theme="light"] .pm h3 { color: #f3eee3; -webkit-text-fill-color: currentColor; }
html[data-theme="light"] .pal input { color: #f3eee3; }
""")
open("src/light.css", "w").write("\n".join(lines) + "\n")
print(len(acc), "rules")
